# The helpers the font-table generators share: the header every generated
# source opens with, and the canonical digest a generated table records so the
# unit tier can recompute it from the compiled table. A generated table is data
# nobody edits by hand; build/check_generated.py regenerates it and fails on a
# difference.
"""Shared writer helpers of the font-table generators (imported, not run)."""

from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def header(purpose: list[str], generator: str) -> str:
    """The licence and purpose header of a generated C++ source."""
    lines = ["// SPDX-License-Identifier: Apache-2.0", "// Copyright 2026 The pdfkit authors", "//"]
    lines += [f"// {line}" if line else "//" for line in purpose]
    lines += ["//", f"// Generated by {generator}; build/check_generated.py regenerates it and",
              "// fails on any difference, so it is never edited by hand."]
    return "\n".join(lines) + "\n"


def digest(lines: list[str]) -> str:
    """SHA-256 over the canonical lines, each ended by a line feed."""
    return hashlib.sha256("".join(line + "\n" for line in lines).encode("utf-8")).hexdigest()


def quote(text: str) -> str:
    """A C++ string literal of ASCII text."""
    out = []
    for ch in text:
        if ch in "\\\"":
            out.append("\\" + ch)
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            raise ValueError(f"non-ASCII or control character in {text!r}")
    return '"' + "".join(out) + '"'


def write(path: Path, text: str) -> None:
    """Writes text in UTF-8 with LF line ends."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
